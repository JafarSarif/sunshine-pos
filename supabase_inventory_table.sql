-- ============================================================================
-- ANTIGRAVITY INVENTORY - SUPABASE DEDICATED PRODUCTS TABLE SCHEMA
-- Run this script in the Supabase SQL Editor if you prefer individual relational rows
-- in addition to the automatic Cloud Document sync.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    price NUMERIC(14, 2) NOT NULL,
    cost_price NUMERIC(14, 2) DEFAULT 0.00,
    stock_count INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER DEFAULT 5,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- Upgrade safety
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS cost_price NUMERIC(14, 2) DEFAULT 0.00;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS low_stock_threshold INTEGER DEFAULT 5;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now());

-- High performance barcode & category indexes
CREATE INDEX IF NOT EXISTS idx_products_barcode ON public.products (barcode);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (category);

-- Helper function for auto-updating timestamps
CREATE OR REPLACE FUNCTION public.fn_touch_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Auto-update updated_at timestamp trigger
DROP TRIGGER IF EXISTS trg_touch_products ON public.products;
CREATE TRIGGER trg_touch_products 
    BEFORE UPDATE ON public.products 
    FOR EACH ROW 
    EXECUTE FUNCTION public.fn_touch_updated_at();

-- Enable Row Level Security (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- Allow full access for connected mobile devices and web apps using the anon/publishable key
DROP POLICY IF EXISTS "Enable full access for products" ON public.products;
CREATE POLICY "Enable full access for products" 
    ON public.products 
    FOR ALL 
    USING (true) 
    WITH CHECK (true);

-- Grant permissions to public anon and authenticated roles
GRANT ALL ON TABLE public.products TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;
